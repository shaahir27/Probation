"""Fixture integrity: the tracked synthetic corpus must be able to prove what it claims.

Authority: docs/CHANGES_IMPLEMENTATION_PLAN.md acceptance criterion V07, and docs/PACKS_SPEC.md
section 0.5.

These assertions exist because a silently stale fixture is worse than a missing one. Every fidelity,
identity and chronology test in this suite reads ``tests/fixtures/tiny_synth``, and if that corpus
were regenerated by an older generator -- final state baked into ``world.db`` instead of an initial
state plus a dated footprint stream, or an anonymous world whose owner no resolver can name -- the
engine would still run and report a clean result on evidence that cannot support it. Each check here
targets one of the ways that happens.
"""

import json
from pathlib import Path
from typing import Any

import pytest

from probation.core.identity import normalize_user_addresses
from probation.db.connection import apply_schema, get_connection
from probation.synth.importers import import_calendar, import_files, import_mail
from probation.synth.world import SimWorld
from probation.workers.ingestor import ingest_situations


@pytest.fixture
def fixture_world(writable_world_db: Path) -> Any:
    """Open a private copy of the world database for the checks that need no engine connection."""
    with SimWorld(writable_world_db) as world:
        yield world


def test_the_world_declares_that_it_stores_its_initial_state(fixture_world: SimWorld) -> None:
    """A world whose stored columns are the *final* state cannot be projected backwards safely."""
    assert fixture_world.stores_initial_state, (
        "world.db does not declare state_model='initial', so its labels and RSVP statuses may be "
        "the end of the story; as-of projections would then hand a resolver an outcome that has "
        "not happened yet (CONTRACT I-6)"
    )


def test_the_world_carries_a_dated_footprint_stream(fixture_world: SimWorld) -> None:
    """The footprints are the only thing that turns an initial state into an observable history."""
    actions = fixture_world.get_user_actions()
    assert actions, (
        "world.db has no user_actions rows, so nothing in it ever changed and every outcome "
        "collapses to whatever was baked into the stored columns"
    )
    assert all(str(a["acted_at"]).strip() for a in actions), "footprint without a timestamp"


def test_the_world_names_the_owner_the_truth_labels_expect(
    fixture_world: SimWorld, tiny_synth_dir: Path
) -> None:
    """An anonymous world attributes no sent mail and no RSVP, hollowing every outcome."""
    assert fixture_world.user_addresses is not None, (
        "world.db does not self-describe its owner, so a reopened world is anonymous"
    )
    persona = json.loads((tiny_synth_dir / "persona.json").read_text("utf-8"))
    assert fixture_world.user_addresses == normalize_user_addresses(persona["email"])


def test_the_tracked_corpus_joins_one_to_one_with_its_truth(
    tiny_synth_dir: Path, tiny_synth_owner: list[str]
) -> None:
    """V07: every ingested situation has exactly one truth record, and none are left over."""
    conn = get_connection(":memory:")
    apply_schema(conn)
    import_mail(tiny_synth_dir / "mailbox.mbox", conn, user_addresses=tiny_synth_owner)
    import_calendar(tiny_synth_dir / "calendar.ics", conn, user_addresses=tiny_synth_owner)
    import_files(tiny_synth_dir / "files_manifest.json", conn)
    ingest_situations(conn)

    truth: dict[str, Any] = json.loads((tiny_synth_dir / "truth.json").read_text(encoding="utf-8"))
    rows = conn.execute("SELECT id, family, raw_item_id FROM situations;").fetchall()
    assert rows, "the fixture ingests no situations"

    ids = [str(r["id"]) for r in rows]
    assert len(ids) == len(set(ids)), "situation ids are not unique"
    orphans = sorted({i for i in ids if i not in truth})[:5]
    assert not orphans, f"situations with no truth record: {orphans}"
    leftover = sorted(set(truth) - set(ids))[:5]
    assert not leftover, f"truth records that were never ingested: {leftover}"

    mismatched = [
        (str(r["id"]), str(r["family"]), truth[str(r["id"])]["family"])
        for r in rows
        if str(r["family"]) != truth[str(r["id"])]["family"]
    ]
    assert not mismatched, f"family disagrees between the corpus and its truth: {mismatched[:5]}"

    raw = conn.execute(
        "SELECT raw_item_id, COUNT(*) AS n FROM situations GROUP BY raw_item_id HAVING n > 1;"
    ).fetchall()
    assert not raw, f"one raw item produced several situations: {[tuple(r) for r in raw][:5]}"

    row = conn.execute("SELECT COUNT(*) FROM raw_items WHERE item_kind = 'mail_sent';").fetchone()
    assert row[0] > 0, "the owner identity matched no message, so the import classified nothing"
    conn.close()


def test_the_rendered_file_tree_holds_every_moved_file(
    tiny_synth_dir: Path, fixture_world: SimWorld
) -> None:
    """A truth label with no file behind it makes its whole family unevaluable."""
    moved = [
        a
        for a in fixture_world.get_user_actions()
        if str(a["action_type"]).startswith("MOVE_TO_FOLDER")
    ]
    assert moved, "the fixture renders no file moves, so file_destination cannot be scored"
    for action in moved:
        destination = str((action.get("details") or {}).get("destination_path") or "")
        assert destination, f"move footprint {action['id']} has no destination path"
        assert (tiny_synth_dir / "fs" / destination).exists(), (
            f"{destination} was claimed as a move target but is not in the rendered fs/ tree"
        )
