"""Pydantic schemas and core domain types.

Authority: docs/CONTRACT.md section 4 and docs/DATA_MODEL.md.
"""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from probation.core.enums import ActionStatus, EvidenceStrength, GateDecision, LicenceLevel


class BaseDomainModel(BaseModel):
    """Base class for domain data structures."""

    model_config = ConfigDict(extra="ignore", frozen=True, populate_by_name=True)


class Situation(BaseDomainModel):
    """Normalized atomic decision point extracted from raw footprints."""

    id: str
    pack: str
    family: str
    raw_item_id: str
    occurred_at: str
    sender_key: str | None = None
    content_hash: str
    redacted_text: str | None = None
    hands_off_reason: str | None = None
    variant: str = ""
    created_at: str = ""

    @property
    def situation_id(self) -> str:
        """Alias for backward compatibility."""
        return self.id


class Features(BaseDomainModel):
    """Deterministic and reader-extracted features for a situation."""

    situation_id: str
    deterministic: dict[str, float | str | bool]
    reader: dict[str, Any] | None = None
    reader_ok: bool
    featurizer_version: str
    model_id: str | None = None
    prompt_version: str | None = None
    features_hash: str
    created_at: str = ""
    provenance_json: str | None = None


class Proposal(BaseDomainModel):
    """Action recommendation generated by the policy before observing outcome."""

    id: str
    situation_id: str
    family: str
    class_key: str
    action: str
    probs: dict[str, float] = Field(default_factory=dict)
    p_max: float
    novelty: float = 0.0
    novel: bool
    licence_level: int = 0
    cap: int = 0
    gate: GateDecision
    reasons: list[str] = Field(default_factory=list)
    params: dict[str, Any] = Field(default_factory=dict)
    explanation: dict[str, Any] = Field(default_factory=dict)
    web: dict[str, Any] = Field(default_factory=dict)
    policy_version: str
    features_hash: str
    audit_holdout: bool = False
    proposed_at: str
    ledger_seq: int = 0

    @property
    def proposal_id(self) -> str:
        """Alias for backward compatibility."""
        return self.id

    @property
    def predicted_prob(self) -> float:
        """Alias for backward compatibility."""
        return self.p_max

    @property
    def gate_decision(self) -> GateDecision:
        """Alias for backward compatibility."""
        return self.gate


class Outcome(BaseDomainModel):
    """Observed human or system outcome for a situation."""

    situation_id: str
    observed_action: str
    strength: EvidenceStrength = EvidenceStrength.STRONG
    source: str = "footprint"
    observed_at: str = ""
    known_at: str
    details: dict[str, Any] = Field(default_factory=dict)
    ledger_seq: int = 0

    @property
    def action(self) -> str:
        """Alias for observed_action."""
        return self.observed_action

    @property
    def tier(self) -> str:
        """Alias for strength."""
        return str(self.strength)


class Action(BaseDomainModel):
    """Side-effect performed or held by the Executor."""

    id: str
    proposal_id: str
    pack: str
    type: str
    params: dict[str, Any] = Field(default_factory=dict)
    level_required: int
    recallable: bool
    status: ActionStatus = ActionStatus.PENDING
    hold_until: str | None = None
    undo: dict[str, Any] | None = None
    created_at: str
    updated_at: str
    executed_at: str | None = None


class LicenceView(BaseDomainModel):
    """Derived permission view for a (class_key, action) pair."""

    class_key: str
    action: str
    level: LicenceLevel
    lower_bound: float
    lb_strong: float = 0.0
    lb_all: float = 0.0
    exam_ok: bool = False
    n_strong: int
    k_strong: int
    n_all: int
    k_all: int
    n_recent: int
    exam_run_id: str | None = None
    valid_until: str
    reasons: list[str] = Field(default_factory=list)


# Alias for LicenceView
Licence = LicenceView


class UserResponse(BaseDomainModel):
    """Explicit human feedback or override from API."""

    id: str
    proposal_id: str
    action_id: str | None = None
    response: str
    edited_action: str | None = None
    responded_at: str


class LedgerEntry(BaseDomainModel):
    """Tamper-evident, hash-chained ledger event."""

    seq: int
    kind: str
    ref_id: str
    payload_json: str
    prev_hash: str
    hash: str
    created_at: str


class ExposureRecord(BaseDomainModel):
    """Redaction audit log tracking token exposure to external LLMs."""

    id: str
    situation_id: str | None = None
    call_kind: str
    model_id: str
    tokens_in: int
    tokens_out: int
    redaction_counts: dict[str, int] = Field(default_factory=dict)
    cost_usd: float
    created_at: str


class RawItem(BaseDomainModel):
    """Normalized raw record imported from sources."""

    id: str
    source_id: str
    pack: str
    item_kind: str
    source_ref: str
    occurred_at: str
    known_at: str
    payload_json: str
    content_hash: str


class Source(BaseDomainModel):
    """Origin source descriptor."""

    id: str
    pack: str
    kind: str
    ref: str
    imported_at: str


class RedactionResult(BaseDomainModel):
    """Output of local PII redaction pipeline.

    `counts` are replacements actually performed in the sent text; `unique` is how many
    distinct values each type covered. Only tokens listed in `restorable` may ever be
    mapped back, and a placeholder-shaped token that was already in the source text is
    excluded from it, so injected text cannot earn restoration authority.
    """

    text: str
    counts: dict[str, int]
    restore_map: dict[str, str]
    unique: dict[str, int] = Field(default_factory=dict)
    restorable: frozenset[str] = frozenset()
    truncated: bool = False

    def __iter__(self) -> Any:
        return iter((self.text, self.restore_map, self.counts))


class ActionSpec(BaseDomainModel):
    """Specification of an action in a pack's action catalog."""

    type: str
    recallable: bool
    base_cap: int
    loss: float


class ReaderSpec(BaseDomainModel):
    """Specification of an LLM reader prompt and schema for a pack."""

    prompt_id: str
    prompt_version: str
    json_schema: dict[str, Any]
    redaction_profile: str


class ExamOperator(BaseDomainModel):
    """Perturbation operator for counterfactual exam board evaluation."""

    name: str
    engine: str  # "code" | "llm"
    expectation: str  # "invariant" | "no_more_autonomous"
    critical: bool = False
    validator_name: str = ""


class ExecResult(BaseDomainModel):
    """Result of an action execution or undo operation."""

    success: bool
    action_id: str
    error: str | None = None
    undo_data: dict[str, Any] | None = None


class Habit(BaseDomainModel):
    """Mined habit association rule from historical decisions."""

    id: str
    family: str
    clue: str
    clue_value: str
    action: str
    k: int
    n: int
    lift: float
    q_value: float
    statement: str
    examples: list[str] = Field(default_factory=list)
    status: str = "active"  # "active" | "denied"
    created_at: str


class Chain(BaseDomainModel):
    """Mined cross-tool sequence association rule."""

    id: str
    trigger_class_key: str
    follow_action: str
    k: int
    n: int
    base_rate: float
    lift: float
    status: str = "active"  # "active" | "retired"
    created_at: str
