"""Pydantic schemas and core domain types.

Authority: docs/CONTRACT.md section 4 and docs/DATA_MODEL.md.
"""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from probation.core.enums import GateDecision, LicenceLevel


class BaseDomainModel(BaseModel):
    """Base class for domain data structures."""

    model_config = ConfigDict(extra="forbid", frozen=True)


class Situation(BaseDomainModel):
    """Normalized atomic decision point extracted from raw footprints."""

    situation_id: str
    pack: str
    item_id: str
    occurred_at: str
    title: str
    raw_ref: str
    metadata: dict[str, Any] = Field(default_factory=dict)


class Proposal(BaseDomainModel):
    """Action recommendation generated by the policy before observing outcome."""

    proposal_id: str
    situation_id: str
    proposed_at: str
    pack: str
    class_key: str
    action: str
    predicted_prob: float
    gate_decision: GateDecision
    explanation: str
    novel: bool
    features_hash: str
    web_json: str | None = None


class Outcome(BaseDomainModel):
    """Observed human or system outcome for a situation."""

    outcome_id: str
    situation_id: str
    known_at: str
    action: str
    tier: str  # STRONG | WEAK
    is_undo: bool = False


class Licence(BaseDomainModel):
    """Derived permission for an autonomous action type."""

    class_key: str
    action: str
    level: LicenceLevel
    as_of: str
    lb_score: float
    n_count: int
    exam_ok: bool
    expires_at: str


class LedgerEntry(BaseDomainModel):
    """Tamper-evident, hash-chained ledger event."""

    seq: int
    prev_hash: str
    hash: str
    event_type: str
    payload_json: str
    created_at: str


class ExposureRecord(BaseDomainModel):
    """Redaction audit log tracking token exposure to external LLMs."""

    call_id: str
    created_at: str
    model: str
    prompt_id: str
    tokens_in: int
    tokens_out: int
    redacted_items_count: int
